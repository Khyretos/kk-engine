#!/usr/bin/env python3
"""Prints the Arabic joining table for engine/src/Localization.cpp from Unicode's own data
(the presentation forms FE70-FEFF and their decompositions), so nothing is typed from memory.

    python3 tools/i18n/gen_arabic_table.py > /tmp/arabic_table.inc

One row per base letter: {base, isolated, final, initial, medial}, 0 where a form does not exist.
A letter with an initial form joins to the letter after it (dual-joining); a letter with only
isolated and final forms joins to the letter before it only (right-joining)."""
import unicodedata

forms = {}
for cp in list(range(0xFB50, 0xFDFF)) + list(range(0xFE70, 0xFEFF)):
    d = unicodedata.decomposition(chr(cp))
    parts = d.split()
    if len(parts) != 2 or parts[0] not in ("<isolated>", "<final>", "<initial>", "<medial>"):
        continue
    base = int(parts[1], 16)
    if not 0x0621 <= base <= 0x06D3 and base not in (0x0640,):
        continue
    forms.setdefault(base, {})[parts[0][1:-1]] = cp

rows = []
for base in sorted(forms):
    f = forms[base]
    rows.append((base, f.get("isolated", 0), f.get("final", 0), f.get("initial", 0), f.get("medial", 0)))
print("// Generated by tools/i18n/gen_arabic_table.py from Unicode's presentation forms: do not edit.")
print("const ArabicForms kArabicForms[] = {")
for r in rows:
    print("    { 0x%04X, 0x%04X, 0x%04X, 0x%04X, 0x%04X }," % r)
print("};")

# The lam-alef ligatures (lam followed by an alef): {alef, isolated, final}.
lig = []
for cp in range(0xFEF5, 0xFEFD):
    d = unicodedata.decomposition(chr(cp)).split()
    if len(d) == 3 and d[0] in ("<isolated>", "<final>"):
        lig.append((int(d[2], 16), d[0][1:-1], cp))
alefs = sorted({a for a, _, _ in lig})
print("const ArabicLigature kLamAlef[] = {")
for a in alefs:
    iso = next(cp for x, k, cp in lig if x == a and k == "isolated")
    fin = next(cp for x, k, cp in lig if x == a and k == "final")
    print("    { 0x%04X, 0x%04X, 0x%04X }," % (a, iso, fin))
print("};")
